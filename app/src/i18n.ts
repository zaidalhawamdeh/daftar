let current: Lang = 'en';

export function setLang(l: Lang): void {
  current = l;
  document.documentElement.lang = l;
  document.documentElement.dir = l === 'ar' ? 'rtl' : 'ltr';
}

export function lang(): Lang {
  return current;
}

export function t(key: string): string {
  return current === 'ar' ? (AR[key] ?? key) : key;
}

