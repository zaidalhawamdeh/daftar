// How much of QuickBooks Desktop's feature list Daftar delivers today, measured, not estimated.

import { readFileSync } from 'node:fs';
import { COMMANDS } from '../core/commands.ts';

export interface Feature {
  id: string;
  area: string;
  feature: string;
  command: string | null;
  ref?: string;
}

// Entry points that live outside the command registry because they create the company itself.
const ENTRY_POINTS = new Set(['company.create']);

const here = new URL('.', import.meta.url);

export function loadCatalog(): Feature[] {
  const doc = JSON.parse(readFileSync(new URL('quickbooks-desktop.json', here), 'utf8')) as { features: Feature[] };
  return doc.features;
}

export function loadFloor(): number {
  return (JSON.parse(readFileSync(new URL('parity-floor.json', here), 'utf8')) as { live: number }).live;
}

export function isLive(f: Feature): boolean {
  return f.command !== null && (COMMANDS.has(f.command) || ENTRY_POINTS.has(f.command));
}

export interface Parity {
  live: number;
  total: number;
  byArea: { area: string; live: number; total: number }[];
  unknownCommands: string[];
}

export function parity(features = loadCatalog()): Parity {
  const areas = new Map<string, { live: number; total: number }>();
  const unknownCommands: string[] = [];
  let live = 0;
  for (const f of features) {
    const a = areas.get(f.area) ?? { live: 0, total: 0 };
    a.total++;
    if (isLive(f)) {
      a.live++;
      live++;
    } else if (f.command !== null) {
      unknownCommands.push(`${f.id} → ${f.command}`);
    }
    areas.set(f.area, a);
  }
  return { live, total: features.length, byArea: [...areas].map(([area, v]) => ({ area, ...v })), unknownCommands };
}

export function markdown(p: Parity, features = loadCatalog()): string {
  const pct = (a: number, b: number) => (b ? ((100 * a) / b).toFixed(1) : '0.0');
  const out = [
    '# QuickBooks Desktop parity',
    '',
    'Generated by `npm run parity`: the feature catalog (`catalog/quickbooks-desktop.json`) compared with the live command registry.',
    '',
    `**${p.live} of ${p.total} catalog features are delivered (${pct(p.live, p.total)}%).**`,
    '',
    '| Area | Live | Total |',
    '|---|---|---|',
    ...p.byArea.map((a) => `| ${a.area} | ${a.live} | ${a.total} |`),
    '',
    '## Features',
    '',
    '| | Feature | Command |',
    '|---|---|---|',
    ...features.map((f) => `| ${isLive(f) ? '✅' : '—'} | ${f.feature} | ${f.command && isLive(f) ? '`' + f.command + '`' : ''} |`),
    '',
  ];
  return out.join('\n');
}
